// Rebuilds the three files the world map reads from the Avium Map:
//
//   landmask.png  copied from the Map's public/landmask.png
//   borders.png   national borders traced out of the Map's borders layer
//   cities.js     every placed city with its map position, richest first
//
// Usage: node scripts/sync-map.mjs <path to an avium-map checkout>
// The GitHub workflow runs this on a schedule against a fresh checkout; locally,
// point it at the sibling folder: node scripts/sync-map.mjs "../Avium Map"
//
// The Map's own border drawing (layers/borders.PNG) is gitignored, so this reads
// the committed full-resolution tiles instead (public/tiles/borders/5, 256px tiles
// over the 6000px world padded to 8192) and stitches them back into the drawing.
import sharp from 'sharp'
import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'fs'
import { join, resolve } from 'path'

const map = resolve(process.argv[2] || '../Avium Map')
const out = resolve(import.meta.dirname, '..')
const WORLD = 6000, TILE = 256, Z = 5, GRID = 32, N = 1500

// --- landmask ---------------------------------------------------------------
copyFileSync(join(map, 'public/landmask.png'), join(out, 'landmask.png'))

// --- borders ----------------------------------------------------------------
// Stitch the z5 tiles (skipBlanks drops the empty ones), crop the padding off.
const tiles = []
for (let y = 0; y < GRID; y++) {
  for (let x = 0; x < GRID; x++) {
    const f = join(map, `public/tiles/borders/${Z}/${y}/${x}.png`)
    if (existsSync(f) && x * TILE < WORLD && y * TILE < WORLD) tiles.push({ input: f, left: x * TILE, top: y * TILE })
  }
}
const drawing = await sharp({ create: { width: GRID * TILE, height: GRID * TILE, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } })
  .composite(tiles).png().toBuffer()
const src = await sharp(drawing).extract({ left: 0, top: 0, width: WORLD, height: WORLD })
  .resize(N, N, { kernel: 'nearest' }).ensureAlpha().raw().toBuffer()
const land = await sharp(join(map, 'public/landmask.png')).resize(N, N).greyscale().raw().toBuffer()

// Each nation is a solid colour, separated from its neighbours by a thin clear gap.
// A border is anywhere the 5x5 neighbourhood holds two nations, or a nation and land
// the layer leaves unpainted (colonies and other unfilled territory). Sea never
// counts, so coastlines stay the land mask's job. A class needs 6 of the 25 pixels
// to count, which keeps a fill that stops just short of the coast from drawing it.
const R = 2, MIN = 6
const cls = j => {
  if (src[j + 3] >= 128) return (src[j] >> 4) * 256 + (src[j + 1] >> 4) * 16 + (src[j + 2] >> 4)
  return land[j / 4] > 128 ? -1 : null
}
const mark = new Uint8Array(N * N)
for (let y = R; y < N - R; y++) {
  for (let x = R; x < N - R; x++) {
    const count = new Map()
    for (let dy = -R; dy <= R; dy++) {
      for (let dx = -R; dx <= R; dx++) {
        const c = cls(((y + dy) * N + x + dx) * 4)
        if (c !== null) count.set(c, (count.get(c) || 0) + 1)
      }
    }
    let nations = 0
    for (const [c, k] of count) if (c !== -1 && k >= MIN) nations++
    if (nations >= 2 || (nations === 1 && (count.get(-1) || 0) >= MIN)) mark[y * N + x] = 1
  }
}
// Thin to the outline of each run so the lines stay a pixel or two wide
const ink = Buffer.alloc(N * N * 4)
for (let p = N; p < N * N - N - 1; p++) {
  if (!mark[p] || (mark[p + 1] && mark[p - 1] && mark[p + N] && mark[p - N])) continue
  ink[p * 4] = ink[p * 4 + 1] = ink[p * 4 + 2] = ink[p * 4 + 3] = 255
}
await sharp(ink, { raw: { width: N, height: N, channels: 4 } }).png({ compressionLevel: 9 }).toFile(join(out, 'borders.png'))

// --- cities -----------------------------------------------------------------
const tsv = f => {
  const [head, ...rows] = readFileSync(join(map, 'src/data', f), 'utf8').trim().split('\n').map(l => l.split('\t'))
  return rows.map(r => Object.fromEntries(head.map((h, i) => [h.trim(), (r[i] || '').trim()])))
}
const gdp = new Map(tsv('cities.tsv').map(r => [r.CITY + '|' + r.NATION, +r['GRDP PPP ($)'].replace(/,/g, '') || 0]))
const cities = tsv('coordinates.tsv')
  .filter(r => r.KIND === 'city')
  .map(r => ({ g: gdp.get(r.NAME + '|' + r.NATION) || 0, c: [r.NAME, r.NATION, Math.round(+r.X), Math.round(+r.Y)] }))
  .sort((a, b) => b.g - a.g || a.c[0].localeCompare(b.c[0]))
  .map(r => r.c)
writeFileSync(join(out, 'cities.js'),
  '// Generated by scripts/sync-map.mjs from the Avium Map. Every placed city, richest first: [name, nation, x, y]\n' +
  'var ALL_CITIES = ' + JSON.stringify(cities) + ';\n')

console.log(`landmask copied, ${tiles.length} border tiles traced, ${cities.length} cities`)
